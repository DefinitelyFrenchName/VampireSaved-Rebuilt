"""extract_tables.py — phase 0's tables: the original census's `gameplay` and `fact` columns (SPEC.md §3).

Reads an export of the original (tools/export_original.py) and its own census (`tools/audit_rule5.py` there), aligns
every record with its manifest row (tools/phase0lib.py), and writes one TSV per subject into OUT_DIR:
- the gameplay column: variant_selection, roster, select_wheel, hit_class_mask;
- the fact column, under facts/: one table per TOML kind (`facts/<kind>.tsv`, top-level keys in `facts/top.tsv`) and
  one per JSON manifest (`facts/json_<path>.tsv`); values listed in facts/held.tsv are written `HELD:sha1=...`.
Each file's header names the pin and the SHA-1 of every manifest it was read from; the tool prints the same. The
format is docs/project/tables/README.md. facts/held.tsv is hand-written and never touched here.

Usage: python3 tools/extract_tables.py <export root> <pin label> <out dir>
       (pin label: the commit the export was made from, e.g. bf92acd2)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import phase0lib  # noqa: E402

TITLES = {
    "variant_selection": "WHICH ROSTER SLOT EACH PATCH ROW APPLIES TO (rule 5's variant selection)",
    "roster": "THE TENANTS' ROSTER IDS AND DESTINATION SLOT",
    "select_wheel": "THE SELECT WHEEL: ITS LAYOUT POINTER, THE NEW CELLS' ADJACENCY AND THE INBOUND EDGES",
    "hit_class_mask": "THE POKES INTO THE HIT-CLASS / GUARD-MASH RNG MASK TABLE (classed by the address they write)",
}


def title(name):
    if name in TITLES:
        return TITLES[name]
    leaf = name.split("/", 1)[1]
    if leaf.startswith("json_"):
        return "FACTS: the census's records of one JSON manifest"
    if leaf == "top":
        return "FACTS: top-level keys of the TOML manifests"
    return "FACTS: the census's records of every [[%s]] row" % leaf


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__.strip().splitlines()[-2])
    export_root, pin, out = sys.argv[1:]
    total, recs_n = 0, 0
    read = {}
    for column in ("gameplay", "fact"):
        tables, recs, r = phase0lib.aligned_rows(export_root, column)
        read.update(r)
        recs_n += len(recs)
        for name, rows in sorted(tables.items()):
            path = os.path.join(out, name + ".tsv")
            os.makedirs(os.path.dirname(path), exist_ok=True)
            sources = sorted({row[0] for row in rows})
            with open(path, "w") as f:
                f.write("# %s.tsv — %s.\n" % (name.split("/")[-1], title(name)))
                f.write("# GENERATED by tools/extract_tables.py from the original at %s; do not hand-edit before "
                        "phase 0 closes (docs/project/tables/README.md).\n" % pin)
                f.write("# read: %s\n" % ", ".join(
                    "%s %s" % (m, r["build/manifest/" + m][:12]) for m in sources))
                f.write("\t".join(phase0lib.SCHEMA) + "\n")
                for row in rows:
                    f.write("\t".join(row) + "\n")
            total += len(rows)
        print("%-8s census records %5d, tabled %5d in %d tables" % (
            column, len(recs), sum(len(v) for v in tables.values()), len(tables)))
    print("pin %s; census records %d; tabled %d" % (pin, recs_n, total))
    for f, h in sorted(read.items()):
        print("read %s sha1 %s" % (f, h))


if __name__ == "__main__":
    main()
