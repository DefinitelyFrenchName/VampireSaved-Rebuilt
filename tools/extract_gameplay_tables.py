"""extract_gameplay_tables.py — phase 0's first tables: the original's 236 gameplay values (SPEC.md §3).

Reads an export of the original (tools/export_original.py) and its own census (`tools/audit_rule5.py` there), aligns
every record of the census's `gameplay` column with its manifest row (tools/phase0lib.py), and writes one TSV per
subject into OUT_DIR: variant_selection, roster, select_wheel, hit_class_mask. Each file's header names the pin and the
SHA-1 of every manifest it was read from; the tool prints the same. The format is docs/project/tables/README.md.

Usage: python3 tools/extract_gameplay_tables.py <export root> <pin label> <out dir>
       (pin label: the commit the export was made from, e.g. bf92acd2)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import phase0lib  # noqa: E402

TITLES = {
    "variant_selection": "WHICH ROSTER SLOT EACH PATCH ROW APPLIES TO (rule 5's variant selection)",
    "roster": "THE TENANTS' ROSTER IDS AND DESTINATION SLOT",
    "select_wheel": "THE SELECT WHEEL: ITS LAYOUT POINTER, THE NEW CELLS' ADJACENCY AND THE INBOUND EDGES",
    "hit_class_mask": "THE POKES INTO THE HIT-CLASS / GUARD-MASH RNG MASK TABLE (classed by the address they write)",
}


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__.strip().splitlines()[-2])
    export_root, pin, out = sys.argv[1:]
    tables, recs, read = phase0lib.aligned_rows(export_root)
    os.makedirs(out, exist_ok=True)
    sources = ", ".join("%s %s" % (os.path.basename(f), h[:12]) for f, h in sorted(read.items()))
    for name, rows in sorted(tables.items()):
        path = os.path.join(out, name + ".tsv")
        with open(path, "w") as f:
            f.write("# %s.tsv — %s.\n" % (name, TITLES[name]))
            f.write("# GENERATED by tools/extract_gameplay_tables.py from the original at %s; do not hand-edit before "
                    "phase 0 closes (docs/project/tables/README.md).\n" % pin)
            f.write("# read: %s\n" % sources)
            f.write("\t".join(phase0lib.SCHEMA) + "\n")
            for row in rows:
                f.write("\t".join(row) + "\n")
        print("%-22s %4d rows -> %s" % (name, len(rows), path))
    print("pin %s; census gameplay records %d; tabled %d" % (pin, len(recs), sum(len(r) for r in tables.values())))
    for f, h in sorted(read.items()):
        print("read %s sha1 %s" % (f, h))


if __name__ == "__main__":
    main()
