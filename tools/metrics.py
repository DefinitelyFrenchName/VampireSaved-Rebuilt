CLASSES = ("MEASURED", "DERIVED", "ESTIMATED", "INFERRED", "EXTRAPOLATED")
ABSENT = "ABSENT"
COLUMNS = ("session", "section", "metric", "label", "value", "unit", "class", "source", "rule")
FIGURES = os.path.join(ROOT, "docs", "project", "metrics", "figures.tsv")
HEADER = ("# docs/project/metrics/figures.tsv — GENERATED by tools/metrics.py (#3); never hand-edited. One row per figure "
          "per session.\n# class: MEASURED, DERIVED, ESTIMATED, INFERRED, EXTRAPOLATED, or ABSENT (no source holds it; "
          "the value is empty). docs/project/metrics/README.md says what each figure is.\n")
GUARD_MARK = "BLOCKED by guard_readonly"
ACTIVITIES = ("records", "verify", "rework", "author", "measure", "converse")
ACTIVITY_RULE = ("each tool call is classed by its input, first match wins: records (names STATE.md, STATE_HISTORY.md, "
                 "tickets.tsv or docs/project/metrics/, or runs git commit/push or gh); verify (a Bash command running "
                 "tests/, or a measurer or rule-checker agent); rework (an Edit/Write of a file one of the session's "
                 "earlier commits already changed); author (any other Edit/Write/NotebookEdit); measure (everything "
                 "else); a request's working time is split evenly among the tool calls it issued, a request with none "
                 "is converse, AskUserQuestion is converse, and a call's own tool time goes to its class")
SPAN_RULE = "last record's timestamp minus the first's"


def ts(s):
    return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()


def load(path):
    out = []
    for line in open(path, encoding="utf-8", errors="replace"):
        try:
            out.append(json.loads(line))
        except ValueError:
            pass
    return out


def content(r):
    c = (r.get("message") or {}).get("content")
    return c if isinstance(c, list) else []


# ---------------------------------------------------------------- the transcript

def parse(recs):
    """-> the raw material: span, request intervals, tool calls, prompts, usage, the harness's own record"""
    stamps = [ts(r["timestamp"]) for r in recs if r.get("timestamp")]
    t = {"t0": min(stamps), "t1": max(stamps)} if stamps else None
    req = {r["id"]: ts(r["timestamp"]) for r in recs if r.get("type") == "api-request" and r.get("timestamp")}
    last, calls, usage, thinking = {}, {}, {}, 0
    for r in recs:
        if r.get("type") != "assistant" or not r.get("timestamp"):
            continue
        at, ref = ts(r["timestamp"]), r.get("requestRef")
        if ref in req:
            last[ref] = max(last.get(ref, at), at)
        thinking += int(r.get("thinkingDurationMs") or 0)
        m = r.get("message") or {}
        if m.get("id") and isinstance(m.get("usage"), dict):
            usage[m["id"]] = (m.get("model") or "?", m["usage"])  # one message spans several records: once per id
        for c in content(r):
            if c.get("type") == "tool_use":
                calls[c["id"]] = {"start": at, "end": None, "name": c.get("name"), "input": c.get("input") or {},
                                  "request": ref, "error": False, "guard": False}
    prompts = []
    for r in recs:
        if r.get("type") != "user" or not r.get("timestamp"):
            continue
        at = ts(r["timestamp"])
        for c in content(r):
            if isinstance(c, dict) and c.get("type") == "tool_result" and c.get("tool_use_id") in calls:
                k = calls[c["tool_use_id"]]
                k["end"] = at
                k["error"] = bool(c.get("is_error"))
                text = c.get("content") if isinstance(c.get("content"), str) else json.dumps(c.get("content"))
                # a refusal is the hook's own error result; a result merely quoting the message (a gate's output, a
                # survey of an older transcript) is not one (measured R-002: R-001 counted 4 by the text alone, 2 real)
                k["guard"] = k["error"] and re.match(r"PreToolUse:\w+ hook error: .*?" + GUARD_MARK, text or "",
                                                     re.S) is not None
        origin = r.get("origin")
        if isinstance(origin, dict) and origin.get("kind"):
            prompts.append((at, "human" if origin["kind"] == "human" else "background", r.get("promptSource")))
    cost = [r for r in recs if r.get("type") == "cost-state"]
    turns = [r["durationMs"] for r in recs if r.get("type") == "system" and r.get("subtype") == "turn_duration"]
    return {"span": t, "requests": {k: (req[k], last[k]) for k in last}, "unanswered": len(req) - len(last),
            "calls": calls, "prompts": sorted(prompts), "usage": usage, "thinking_ms": thinking,
            "cost": cost[-1] if cost else None, "turns": turns}


def buckets(p, keep=None):
    """-> {bucket: seconds} over the span (see the module docstring); keep(request_id or call) filters a share"""
    t0, t1 = p["span"]["t0"], p["span"]["t1"]
    work = [v for k, v in p["requests"].items() if keep is None or keep(k)]
    ask, tools = [], []
    for c in p["calls"].values():
        if c["end"] is None or (keep is not None and not keep(c)):
            continue
        (ask if c["name"] == "AskUserQuestion" else tools).append((c["start"], c["end"]))
    pts = sorted({t0, t1} | {x for iv in work + ask + tools for x in iv if t0 <= x <= t1})
    out = dict.fromkeys(("working", "maintainer", "tools", "unaccounted"), 0.0)
    idle = []
    for a, b in zip(pts, pts[1:]):
        mid = (a + b) / 2
        if any(x <= mid <= y for x, y in work):
            out["working"] += b - a
        elif any(x <= mid <= y for x, y in ask):
            out["maintainer"] += b - a
        elif any(x <= mid <= y for x, y in tools):
            out["tools"] += b - a
        elif idle and idle[-1][1] == a:
            idle[-1][1] = b
        else:
            idle.append([a, b])
    for a, b in idle:
        inside = [(at, who) for at, who, _ in p["prompts"] if a <= at <= b]
        if keep is not None or not inside:
            out["unaccounted"] += b - a
            continue
        at, who = inside[-1]
        out["maintainer" if who == "human" else "tools"] += at - a
        out["unaccounted"] += b - at
    return out


def activity(p, commits):
    """-> {activity: seconds} by ACTIVITY_RULE"""
    out = dict.fromkeys(ACTIVITIES, 0.0)
    changed = [(c["time"], set(c["files"])) for c in commits]
    by_req = {}
    for c in p["calls"].values():
        by_req.setdefault(c["request"], []).append(c)

    def kind(c):
        name, inp = c["name"], c["input"]
        text = json.dumps(inp)
        path = inp.get("file_path") or inp.get("notebook_path") or ""
        rel = os.path.relpath(path, ROOT) if path.startswith("/") else path
        if name == "AskUserQuestion":
            return "converse"
        if re.search(r"STATE(_HISTORY)?\.md|tickets\.tsv|docs/project/metrics/", text) or (
                name == "Bash" and re.search(r"\bgit (commit|push)\b|\bgh\b", inp.get("command", ""))):
            return "records"
        if (name == "Bash" and re.search(r"\btests/", inp.get("command", ""))) or (
                name == "Agent" and inp.get("subagent_type") in ("measurer", "rule-checker")):
            return "verify"
        if name in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
            if any(at < c["start"] and rel in files for at, files in changed):
                return "rework"
            return "author"
        return "measure"
    for rid, (a, b) in p["requests"].items():
        cs = by_req.get(rid, [])
        if not cs:
            out["converse"] += b - a
        for c in cs:
            out[kind(c)] += (b - a) / len(cs)
    for c in p["calls"].values():
        if c["end"] is not None:
            out[kind(c)] += c["end"] - c["start"]
    return out


# ---------------------------------------------------------------- git and the tree

def git(repo, *a):
    p = subprocess.run(["git", "-C", repo] + list(a), capture_output=True, text=True)
    return p.stdout if p.returncode == 0 else None


def session_commits(repo, key, t0, t1):
    """commits whose subject starts with the key, or whose committer time falls inside the transcript's span"""
    out, cur = [], None
    for line in (git(repo, "log", "--no-merges", "--numstat", "--format=@@%H\t%ct\t%s") or "").splitlines():
        if line.startswith("@@"):
            sha, at, subj = line[2:].split("\t", 2)
            mine = subj.startswith(key + " ") or subj.startswith(key + ":") or (
                t0 is not None and t0 <= int(at) <= t1 + 1)
            cur = {"sha": sha, "time": int(at), "files": [], "ins": 0, "dels": 0} if mine else None
            if cur:
                out.append(cur)
        elif cur and line.strip():
            ins, dels, path = line.split("\t", 2)
            cur["files"].append(path)
            cur["ins"] += int(ins) if ins.isdigit() else 0
            cur["dels"] += int(dels) if dels.isdigit() else 0
    return sorted(out, key=lambda c: c["time"])


def area(path):
    parts = path.split("/")
    return "/".join(parts[:2]) if parts[0] in ("docs", "tests", "tools", ".claude") and len(parts) > 2 else parts[0]


def show(repo, sha, path):
    return git(repo, "show", "%s:%s" % (sha, path))


def table_rows(text):
    return sum(1 for l in (text or "").splitlines() if l and not l.startswith("#") and not l.startswith("manifest\t"))


def transcript_of(repo, key):
    for name in ("STATE.md", "STATE_HISTORY.md"):
        p = os.path.join(repo, name)
        if os.path.exists(p):
            m = re.search(r"(?m)^## Session %s\b.*?transcript `([0-9a-f]{8})" % re.escape(key), open(p).read())
            if m:
                return m.group(1), "%s, the session's heading" % name
    return None, None


# ---------------------------------------------------------------- collect

def collect(key, path, repo, runs, share=None, how=""):
    rows = []

    def F(section, metric, label, value, unit, cls, source, rule=""):
        if cls == ABSENT or value is None:
            rows.append(dict(zip(COLUMNS, (key, section, metric, label, "", unit, ABSENT, source, rule))))
            return
        assert cls in CLASSES, cls
        rows.append(dict(zip(COLUMNS, (key, section, metric, label, value, unit, cls, source, rule))))

    mins = lambda s: round(s / 60, 1)
    p = parse(load(path)) if path and os.path.exists(path) else None
    tid = os.path.basename(path)[:8] if p and p["span"] else None
    tsrc = "transcript %s" % tid if tid else "no transcript"
    t0, t1 = (p["span"]["t0"], p["span"]["t1"]) if tid else (None, None)
    commits = session_commits(repo, key, t0, t1) if not share else []
    # -- time
    if tid:
        F("time", "transcript", "Transcript", tid, "", "MEASURED", how or "--transcript")
        span = t1 - t0
        if share:
            hit = lambda inp: re.search(share, json.dumps(inp)) is not None
            reqs = {c["request"] for c in p["calls"].values() if hit(c["input"])}
            keep = lambda x: (x in reqs) if isinstance(x, str) else hit(x["input"])
            b = buckets(p, keep)
            rule = ("the session's API requests and tool calls whose tool inputs match the regex %r, timed as in "
                    "docs/project/metrics/README.md; the rest of the session did other work, and work on this share "
                    "whose calls do not match (prose, thinking, idle) is not counted, so it undercounts" % share)
            F("time", "span_min", "Whole session span (all its work)", mins(span), "min", "DERIVED", tsrc, SPAN_RULE)
            F("time", "working_min", "Claude working (this share)", mins(b["working"]), "min", "EXTRAPOLATED", tsrc, rule)
            F("time", "tools_min", "Waiting on tools (this share)", mins(b["tools"]), "min", "EXTRAPOLATED", tsrc, rule)
            F("time", "maintainer_min", "Waiting on the maintainer (this share)", mins(b["maintainer"]), "min",
              "EXTRAPOLATED", tsrc, rule + "; only AskUserQuestion waits can be attributed")
            F("time", "calls_in_share", "Tool calls in this share", sum(1 for c in p["calls"].values() if hit(c["input"])),
              "", "ESTIMATED", tsrc, "tool calls whose input matches the regex %r" % share)
        else:
            b = buckets(p)
            rule = "slices of the span given to one bucket each, by precedence (docs/project/metrics/README.md)"
            F("time", "span_min", "Total (session span)", mins(span), "min", "DERIVED", tsrc, SPAN_RULE)
            F("time", "working_min", "Claude working", mins(b["working"]), "min", "DERIVED", tsrc,
              rule + ": inside an API request, from its api-request record to the last assistant record answering it")
            F("time", "tools_min", "Claude waiting on tools", mins(b["tools"]), "min", "DERIVED", tsrc,
              rule + ": inside a tool call other than AskUserQuestion, tool_use to tool_result; or idle until a "
              "prompt of non-human origin (a hand-back, a notification)")
            F("time", "maintainer_min", "Waiting on the maintainer", mins(b["maintainer"]), "min", "DERIVED", tsrc,
              rule + ": inside an AskUserQuestion call, or idle until a prompt of human origin")
            F("time", "unaccounted_min", "Unaccounted", mins(b["unaccounted"]), "min", "DERIVED", tsrc,
              rule + ": idle after the last prompt of a stretch, or idle with no prompt")
        whole = " (whole session)" if share else ""
        F("time", "thinking_min", "Thinking (inside working)" + whole, mins(p["thinking_ms"] / 1000), "min",
          "MEASURED", tsrc,
          "sum of thinkingDurationMs over assistant records")
        F("time", "turns_timed", "Turns carrying a duration" + whole, len(p["turns"]), "", "MEASURED", tsrc)
        F("time", "turns_timed_min", "Their duration" + whole, mins(sum(p["turns"]) / 1000), "min", "MEASURED", tsrc,
          "sum of system/turn_duration durationMs")
        cs = p["cost"]
        csrc = tsrc + ", its cost-state record" if cs else tsrc + " (no cost-state record)"
        get = lambda k: (cs or {}).get(k)
        hmin = lambda k: mins(get(k) / 1000) if get(k) is not None else None
        for metric, label, field in (("harness_duration_min", "Harness: session duration", "totalDuration"),
                                     ("harness_api_min", "Harness: API time", "totalAPIDuration"),
                                     ("harness_tool_min", "Harness: tool time", "totalToolDuration")):
            F("time", metric, label + whole, hmin(field), "min", "MEASURED" if hmin(field) is not None else ABSENT, csrc,
              "%s / 60000" % field)
        F("cost", "cost_usd", "Cost as the harness computed it", round(get("totalCostUSD"), 2) if get(
            "totalCostUSD") is not None else None, "USD", "MEASURED" if get("totalCostUSD") is not None else ABSENT,
          csrc)
        if cs and not share:
            api, tool = get("totalAPIDuration") / 1000, (get("totalToolDuration") or 0) / 1000
            F("time", "working_vs_harness_pct", "Claude working vs harness API time", round(
                100 * (b["working"] - api) / api, 1) if api else None, "%", "DERIVED", csrc,
              "(working minus the harness's API time) / the harness's API time")
            tools_only = sum(c["end"] - c["start"] for c in p["calls"].values()
                             if c["end"] is not None and c["name"] != "AskUserQuestion")
            F("time", "tools_vs_harness_pct", "Tool calls' own time vs harness tool time", round(
                100 * (tools_only - tool) / tool, 1) if tool else None, "%", "DERIVED", csrc,
              "(sum of tool_use-to-tool_result over calls other than AskUserQuestion, minus the harness's tool time) "
              "/ the harness's tool time")
        if not share:
            act = activity(p, commits)
            for a in ACTIVITIES:
                F("activity", "act_%s_min" % a, "Activity: %s" % a, mins(act[a]), "min", "ESTIMATED", tsrc,
                  ACTIVITY_RULE)
            hp = [x for x in p["prompts"] if x[1] == "human"]
            F("events", "prompts_typed", "Maintainer prompts, typed", sum(1 for x in hp if x[2] == "typed"), "",
              "MEASURED", tsrc)
            F("events", "prompts_queued", "Maintainer prompts, queued while Claude worked",
              sum(1 for x in hp if x[2] == "queued"), "", "MEASURED", tsrc)
            F("events", "asks", "Questions asked (AskUserQuestion)",
              sum(1 for c in p["calls"].values() if c["name"] == "AskUserQuestion"), "", "MEASURED", tsrc)
            F("events", "tool_calls", "Tool calls", len(p["calls"]), "", "MEASURED", tsrc)
            names = {}
            for c in p["calls"].values():
                names[c["name"]] = names.get(c["name"], 0) + 1
            for n in sorted(names):
                F("events", "tool_%s" % n, "Tool calls: %s" % n, names[n], "", "MEASURED", tsrc)
            F("events", "bg_launched", "Background launches", sum(1 for c in p["calls"].values() if c["input"].get(
                "run_in_background")), "", "MEASURED", tsrc)
            F("events", "tool_errors", "Tool results marked error",
              sum(1 for c in p["calls"].values() if c["error"]), "", "MEASURED", tsrc)
            F("health", "guard_refusals", "Read-only guard refusals",
              sum(1 for c in p["calls"].values() if c["guard"]), "", "MEASURED", tsrc,
              "tool results marked error whose text begins `PreToolUse:<tool> hook error:` and carries %r" % GUARD_MARK)
            F("events", "requests_unanswered", "API requests with no answer on record", p["unanswered"], "",
              "MEASURED", tsrc)
            # -- tokens, the orchestrator by model, then the workers
            models = {}
            for model, u in p["usage"].values():
                m = models.setdefault(model, {"out": 0, "think": 0, "in": 0})
                m["out"] += int(u.get("output_tokens") or 0)
                m["think"] += int((u.get("output_tokens_details") or {}).get("thinking_tokens") or 0)
                m["in"] += sum(int(u.get(f) or 0) for f in ("input_tokens", "cache_creation_input_tokens",
                                                           "cache_read_input_tokens"))
            urule = "usage of each assistant message, once per message id"
            main_out = 0
            for model in sorted(models):
                m = models[model]
                main_out += m["out"]
                F("tokens", "out_%s" % model, "Output tokens, orchestrator (%s)" % model, m["out"], "tokens",
                  "MEASURED", tsrc, urule)
                F("tokens", "think_%s" % model, "of which thinking (%s)" % model, m["think"], "tokens", "MEASURED",
                  tsrc, urule)
                F("tokens", "in_%s" % model, "Input tokens incl. cache, orchestrator (%s)" % model, m["in"], "tokens",
                  "MEASURED", tsrc, urule)
            # the harness's per-model totals cover the orchestrator, the workers and the harness's own small calls
            all_out = None
            if cs and isinstance(cs.get("modelUsage"), dict):
                all_out = 0
                for model in sorted(cs["modelUsage"]):
                    u = cs["modelUsage"][model]
                    all_out += int(u.get("outputTokens") or 0)
                    F("tokens", "harness_out_%s" % model, "Harness: output tokens, all agents (%s)" % model,
                      int(u.get("outputTokens") or 0), "tokens", "MEASURED", csrc, "modelUsage.outputTokens")
            wsrc = tsrc + "/subagents"
            workers = sorted(glob.glob(path[:-len(".jsonl")] + "/subagents/*.jsonl"))
            F("workers", "workers", "Workers spawned", len(workers), "", "MEASURED", wsrc)
            kinds, w_span, w_work = {}, 0.0, 0.0
            for w in workers:
                meta = w[:-len(".jsonl")] + ".meta.json"
                kind = json.load(open(meta)).get("agentType", "?") if os.path.exists(meta) else "?"
                kinds[kind] = kinds.get(kind, 0) + 1
                wp = parse(load(w))
                if wp["span"]:
                    w_span += wp["span"]["t1"] - wp["span"]["t0"]
                    w_work += buckets(wp)["working"]
            for k in sorted(kinds):
                F("workers", "workers_%s" % k, "Workers: %s" % k, kinds[k], "", "MEASURED", wsrc)
            # a worker transcript's usage.output_tokens is a streaming snapshot (16-25 a message, measured R-002), so
            # the workers' tokens come from the harness's totals, never from their transcripts
            w_out = all_out - main_out if all_out is not None else None
            orule = ("the harness's output tokens over all models minus the orchestrator's transcript usage; includes "
                     "the harness's own small calls (titles)")
            F("workers", "worker_out", "Output tokens, workers", w_out, "tokens", "DERIVED" if w_out is not None
              else ABSENT, csrc, orule)
            F("workers", "worker_span_min", "Workers' spans, summed", mins(w_span), "min", "DERIVED", wsrc,
              "sum over workers of " + SPAN_RULE + "; workers can run in parallel with each other and with Claude")
            F("workers", "worker_working_min", "Workers working, summed", mins(w_work), "min", "DERIVED", wsrc,
              "sum over workers of their working bucket, timed as the orchestrator's")
            F("workers", "worker_out_share_pct", "Workers' share of output tokens", round(100 * w_out / all_out, 1)
              if w_out is not None and all_out else None, "%", "DERIVED" if w_out is not None and all_out
              else ABSENT, csrc, orule + ", over the harness's total")
    else:
        F("time", "transcript", "Transcript", None, "", ABSENT, how or "no transcript id on record or file gone")
    if share:
        return rows
    # -- git: what the session committed, by area
    gsrc = "git log"
    grule = "the session's commits: subject starting with the key, or committer time inside the transcript's span"
    F("output", "commits", "Commits", len(commits), "", "DERIVED", gsrc, grule)
    F("output", "files", "Files changed (sum over commits)", sum(len(c["files"]) for c in commits), "", "DERIVED",
      gsrc, grule)
    F("output", "insertions", "Lines inserted", sum(c["ins"] for c in commits), "", "DERIVED", gsrc, grule)
    F("output", "deletions", "Lines deleted", sum(c["dels"] for c in commits), "", "DERIVED", gsrc, grule)
    areas = {}
    for c in commits:
        for f in c["files"]:
            areas[area(f)] = areas.get(area(f), 0) + 1
    for a in sorted(areas):
        F("area", "area_%s" % a, "Files changed in %s" % a, areas[a], "", "DERIVED", gsrc,
          grule + "; the area is a path's first component, or its first two under docs/, tests/, tools/, .claude/")
    # -- progress and health, read from the tree at the session's last commit
    last = commits[-1]["sha"] if commits else None
    at = "the tree at %s, the session's last commit" % (last[:8] if last else "?")
    if last:
        listing = (git(repo, "ls-tree", "-r", "--name-only", last) or "").splitlines()
        tables = [f for f in listing if f.startswith("docs/project/tables/") and f.endswith(".tsv")]
        fact = [f for f in tables if f.startswith("docs/project/tables/facts/") and not f.endswith("/held.tsv")]
        gameplay = [f for f in tables if f.count("/") == 3]
        F("progress", "tabled_gameplay", "Phase 0: gameplay values tabled",
          sum(table_rows(show(repo, last, f)) for f in gameplay), "", "MEASURED", at, "rows of the top-level tables")
        F("progress", "tabled_fact", "Phase 0: facts tabled", sum(table_rows(show(repo, last, f)) for f in fact), "",
          "MEASURED", at, "rows of the tables under facts/, held.tsv aside")
        F("progress", "tabled_code", "Phase 0: generator constants tabled",
          sum(table_rows(show(repo, last, f)) for f in tables if f.startswith("docs/project/tables/code/")), "",
          "MEASURED", at, "rows of the tables under code/")
        spec = show(repo, last, "SPEC.md") or ""
        for col, rx in (("gameplay", r"gameplay values \d+ in tables of ([\d,]+)"),
                        ("fact", r"facts \d+ in tables\s+and [\d,]+ derived of ([\d,]+)"),
                        ("code", r"code constants ([\d,]+) baked")):
            m = re.search(rx, spec)
            F("progress", "census_%s" % col, "Phase 0: the original's census, %s column" % col,
              int(m.group(1).replace(",", "")) if m else None, "", "MEASURED" if m else ABSENT,
              "SPEC.md §1 at %s (the original's census at 6dee2be7)" % (last[:8]))
        gates = [f for f in listing if re.match(r"tests/test_[^/]+\.py$", f)]
        F("progress", "gates", "Gates in the tree", len(gates), "", "MEASURED", at, "tests/test_*.py")
        ported = [g for g in gates if re.search(r"(?im)^\s*ported from\b", show(repo, last, g) or "")]
        F("progress", "gates_ported", "Gates ported from the original", len(ported), "", "MEASURED", at,
          "tests/test_*.py with a line starting `Ported from` (SPEC.md §5.3: the port records the original gate)")
        inv = [l.split("\t") for l in (show(repo, last, "docs/tests_inventory.tsv") or "").splitlines()
               if l and not l.startswith("#") and not l.startswith("gate\t")]
        F("progress", "gates_original", "The original's gates (the inventory)", len(inv), "", "MEASURED",
          "docs/tests_inventory.tsv at %s" % last[:8])
        for cls in sorted({r[7] for r in inv if len(r) > 7}):
            F("progress", "gates_original_%s" % cls, "of class %s" % cls, sum(1 for r in inv if len(r) > 7 and
                                                                             r[7] == cls), "", "MEASURED",
              "docs/tests_inventory.tsv at %s" % last[:8])
        tk = [l.split("\t") for l in (show(repo, last, "docs/project/tickets.tsv") or "").splitlines()
              if l and not l.startswith("#") and not l.startswith("number\t")]
        F("health", "tickets_open", "Open tickets", sum(1 for r in tk if len(r) > 2 and r[2] == "open"), "",
          "MEASURED", "docs/project/tickets.tsv at %s" % last[:8])
        state = show(repo, last, "STATE.md") or ""
        m = re.search(r"(?ms)^## Decisions pending[^\n]*\n(.*?)(?=^## |^# |\Z)", state)
        items = re.findall(r"(?m)^(?:\d+\.|-) ", m.group(1)) if m else None
        F("health", "decisions_pending", "Decisions pending", len(items) if m else None, "",
          "MEASURED" if m else ABSENT, "STATE.md at %s" % last[:8], "numbered or bulleted items of the section")
        unpushed = sum(1 for c in commits if subprocess.run(
            ["git", "-C", repo, "merge-base", "--is-ancestor", c["sha"], "origin/main"]).returncode != 0)
        F("health", "unpushed", "Session commits not on origin/main", unpushed, "", "MEASURED",
          "git merge-base --is-ancestor, at collection (%s)" % datetime.now().strftime("%Y-%m-%d %H:%M"))
        has_rc = any(f.startswith("tests/rulecheck/") for f in listing)
        F("health", "rule_checker_runs", "Rule-checker runs before an action ([VSR-48])", None if has_rc else 0, "",
          ABSENT if has_rc else "DERIVED", at, "" if has_rc else
          "no rule-checker tool or ledger exists in the tree (docs/project/rule_checker.md is its spec), so none ran")
    # -- gates, from the run log
    log = [r for r in runlog.read(runs) if t0 is not None and t0 <= ts(r["start"]) <= t1 + 1]
    rsrc = "build/runs/runs.jsonl"
    rrule = "runs whose start falls inside the transcript's span"
    if not log:
        F("gates", "gate_runs", "Gate runs", None, "", ABSENT, rsrc + " (no run inside the session's span)", rrule)
    else:
        F("gates", "gate_runs", "Gate runs", len(log), "", "DERIVED", rsrc, rrule)
        red = 0.0
        for g in sorted({r["gate"] for r in log}):
            mine = [r for r in log if r["gate"] == g]
            normal = [r for r in mine if r["mode"] == "normal"]
            ctl = [r for r in mine if r["mode"] != "normal"]
            if normal:
                r = normal[-1]
                F("gates", "%s_verdict" % g, "%s: last verdict" % g, r["verdict"], "", "MEASURED", rsrc)
                F("gates", "%s_cases" % g, "%s: cases" % g, r["cases"], "", "MEASURED" if r["cases"] is not None
                  else ABSENT, rsrc)
                F("gates", "%s_declared" % g, "%s: controls declared" % g, len(r["controls_declared"]), "",
                  "MEASURED", rsrc)
                F("gates", "%s_fired" % g, "%s: controls fired" % g, len(r["controls_fired"]), "", "MEASURED", rsrc)
                F("gates", "%s_seconds" % g, "%s: runtime" % g, r["duration_s"], "s", "MEASURED", rsrc)
            F("gates", "%s_runs" % g, "%s: runs" % g, len(normal), "", "DERIVED", rsrc, rrule)
            if ctl:
                F("gates", "%s_modes_honoured" % g, "%s: control modes HONOURED" % g,
                  sum(1 for r in ctl if r["verdict"] == "FAIL"), "", "DERIVED", rsrc,
                  rrule + "; a control mode is honoured when the gate reached its own FAIL")
                F("gates", "%s_modes" % g, "%s: control-mode runs" % g, len(ctl), "", "DERIVED", rsrc, rrule)
            for a, b in zip(normal, normal[1:] + [None]):
                if a["verdict"] == "FAIL":
                    red += (ts(b["start"]) if b else t1) - ts(a["end"])
        F("health", "red_min", "Minutes with a gate red", round(red / 60, 1), "min", "DERIVED", rsrc,
          "per gate, from the end of a normal run that FAILed to the start of its next normal run (or the session's "
          "end), summed; control-mode runs aside")
    return rows


def read_figures(path):
    if not os.path.exists(path):
        return []
    out = []
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or line.startswith("session\t") or not line.strip():
            continue
        out.append(dict(zip(COLUMNS, line.rstrip("\n").split("\t"))))
    return out


def write_figures(path, rows):
    order = []
    for r in rows:
        if r["session"] not in order:
            order.append(r["session"])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER + "\t".join(COLUMNS) + "\n")
        for s in order:
            for r in rows:
                if r["session"] == s:
                    f.write("\t".join(str(r[c]).replace("\t", " ").replace("\n", " ") for c in COLUMNS) + "\n")


def check(path):
    bad = 0
    rows = read_figures(path)
    for r in rows:
        why = ("class %r" % r["class"]) if r["class"] not in CLASSES + (ABSENT,) else \
              "no source" if not r["source"] else \
              "no rule" if r["class"] not in ("MEASURED", ABSENT) and not r["rule"] else \
              "a value on an ABSENT row" if r["class"] == ABSENT and r["value"] != "" else \
              "no value" if r["class"] != ABSENT and r["value"] == "" else ""
        if why:
            bad += 1
            print("  BAD %s %s: %s" % (r["session"], r["metric"], why))
    print("%d figures, %d bad" % (len(rows), bad))
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sp = ap.add_subparsers(dest="cmd", required=True)
    c = sp.add_parser("collect")
    c.add_argument("key")
    c.add_argument("--transcript")
    c.add_argument("--projects", default=os.path.expanduser(
        "~/.claude/projects/" + re.sub(r"[^A-Za-z0-9]", "-", ROOT)))
    c.add_argument("--repo", default=ROOT)
    c.add_argument("--runs", default=runlog.RUNS)
    c.add_argument("--out", default=FIGURES)
    c.add_argument("--share-pattern")
    dp = sp.add_parser("drop")
    dp.add_argument("key")
    dp.add_argument("--out", default=FIGURES)
    k = sp.add_parser("check")
    k.add_argument("file", nargs="?", default=FIGURES)
    a = ap.parse_args()
    if a.cmd == "check":
        return check(a.file)
    if a.cmd == "drop":
        rows = read_figures(a.out)
        kept = [r for r in rows if r["session"] != a.key]
        if len(kept) == len(rows):
            print("%s: no rows in %s; nothing dropped" % (a.key, os.path.relpath(a.out, ROOT)))
            return 1
        write_figures(a.out, kept)
        print("%s: %d rows dropped from %s" % (a.key, len(rows) - len(kept), os.path.relpath(a.out, ROOT)))
        return 0
    path, how = a.transcript, "--transcript"
    if not path:
        tid, how = transcript_of(a.repo, a.key)
        hits = glob.glob(os.path.join(a.projects, tid + "*.jsonl")) if tid else []
        path = hits[0] if len(hits) == 1 else None
        how = how if path else "no transcript id on the session's STATE heading, or no single file matching it"
    rows = collect(a.key, path, a.repo, a.runs, a.share_pattern, how)
    kept = [r for r in read_figures(a.out) if r["session"] != a.key]
    write_figures(a.out, kept + rows)
    for r in rows:
        print("%-10s %-9s %-28s %12s %-6s %s" % (r["session"], r["section"], r["metric"], r["value"], r["unit"],
                                                 r["class"]))
    print("%s: %d figures written to %s" % (a.key, len(rows), os.path.relpath(a.out, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
