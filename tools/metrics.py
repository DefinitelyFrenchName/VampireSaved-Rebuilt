#!/usr/bin/env python3
"""metrics.py — the session dashboard's figures, every one classed by how it was obtained (#3).

Reads, read-only, what a session already wrote (its transcript, git, the tree, the run log) and writes the session's
rows of docs/project/metrics/figures.tsv: one row per figure, `{value, class, source, rule}` (#3, after the original's
tools/session_metrics.py, its #264). The classes:
  MEASURED      read directly from a record the work wrote (a transcript field, a commit, a table row)
  DERIVED       arithmetic on measured figures; `rule` is the formula
  ESTIMATED     a heuristic classification of measured data; `rule` is the heuristic, and it can be wrong
  INFERRED      a judgement about meaning; `rule` says how it was judged (this tool emits none)
  EXTRAPOLATED  a projection beyond the data, or a backfill from a session that did other work too
A figure no source holds is written with class ABSENT and an empty value, never filled in, so the gap shows.
Values are numbers, a few words of this project's own records (a verdict, a transcript id), never transcript text.

WHERE TIME GOES (section `time`). The session's span (first record to last) is cut at every boundary below and each
slice is given to exactly one bucket, in this order of precedence:
  working      inside an API request of the session: from the `api-request` record to the last assistant record
               answering it (`requestRef`)
  maintainer   inside an AskUserQuestion call (the tool waits on the maintainer, not on a program)
  tools        inside any other tool call: from the assistant record carrying the `tool_use` to the record carrying
               its `tool_result`
  idle         none of the above. An idle stretch is given, up to its LAST prompt, to whoever sent that prompt: the
               maintainer (a user record of origin `human`) or background work (any other origin: a subagent's
               hand-back, a task notification), which counts as tools; what follows the last prompt, or a stretch
               with no prompt in it, is UNACCOUNTED and shown.
The transcript's `cost-state` record, when present, carries the harness's own totals (duration, API time, tool time,
cost); they are MEASURED and printed beside the DERIVED buckets, with the difference, as the method's cross-check.

Written in Python ([VSR-11]): it reads JSON lines and git, like the gates that feed it.

Usage:
  python3 tools/metrics.py collect KEY [--transcript PATH] [--projects DIR] [--repo DIR] [--runs DIR]
        [--out FILE] [--share-pattern TEXT]
      KEY's transcript is the id on its STATE heading (`transcript `<8 hex>``) unless --transcript names it. Replaces
      KEY's rows in --out (default docs/project/metrics/figures.tsv) and prints them. --share-pattern makes the time
      figures a SHARE of a session that also did other work (a backfill): only the requests and tool calls whose tool
      inputs match the pattern (a regex) are counted, and the result is EXTRAPOLATED.
  python3 tools/metrics.py drop KEY [--out FILE]
      removes KEY's rows from the table (a session the maintainer ruled out of it); refuses a key with no rows.
  python3 tools/metrics.py check [FILE]
      every row has a class among the five or ABSENT, a source, a rule unless MEASURED, and a value exactly when not
      ABSENT; exit 1 if not.
Gate: tests/test_metrics.py.
"""
